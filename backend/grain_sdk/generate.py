"""Generates the manifest types of the SDK from schemas/manifest.schema.json: grain_sdk/types.py (a TypedDict) and
packages/ext-sdk/index.d.ts (TypeScript). The hook payload types come from the hook catalog (`grain ext gen-hooks`). Edit the
schema and run

    python -m grain_sdk.generate          # rewrite both files
    python -m grain_sdk.generate --check  # exit 1 if either is out of date

Only the schema features the two files use are supported: objects with properties, additionalProperties maps, arrays,
enums, anyOf, null and the scalar types. A property name must be an identifier.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path
from typing import Any

HERE = Path(__file__).parent
PY_OUT = HERE / "types.py"
TS_OUT = HERE.parents[1] / "packages" / "ext-sdk" / "index.d.ts"
PY_SCALARS = {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "null": "None"}
TS_SCALARS = {"string": "string", "integer": "number", "number": "number", "boolean": "boolean", "null": "null"}


def pascal(*parts: str) -> str:
    return "".join(w[:1].upper() + w[1:] for p in parts for w in re.split(r"[^A-Za-z0-9]+", p) if w)


class Types:
    """Accumulates one named class per object schema, in dependency order, for both languages."""

    def __init__(self) -> None:
        self.py: list[str] = []
        self.ts: list[str] = []

    def of(self, schema: dict[str, Any], name: str) -> tuple[str, str]:
        """(python, typescript) type expressions for a schema; an object with properties becomes a class called `name`."""
        if "enum" in schema:
            return (f"Literal[{', '.join(repr(v) for v in schema['enum'])}]", " | ".join(json.dumps(v) for v in schema["enum"]))
        if "anyOf" in schema:
            parts = [self.of(s, name) for s in schema["anyOf"]]
            return " | ".join(p for p, _ in parts), " | ".join(t for _, t in parts)
        kind = schema.get("type")
        if kind in PY_SCALARS:
            return PY_SCALARS[kind], TS_SCALARS[kind]
        if kind == "array":
            py, ts = self.of(schema["items"], f"{name}Item")
            return f"list[{py}]", f"({ts})[]" if "|" in ts else f"{ts}[]"
        if kind == "object" and schema.get("properties"):
            self.cls(schema, name)
            return name, name
        if kind == "object":
            extra = schema.get("additionalProperties")
            py, ts = self.of(extra, f"{name}Value") if isinstance(extra, dict) else ("Any", "unknown")
            return f"dict[str, {py}]", f"Record<string, {ts}>"
        return "Any", "unknown"

    def cls(self, schema: dict[str, Any], name: str, doc: str = "") -> None:
        required = set(schema.get("required", ()))
        py_fields: list[str] = []
        ts_fields: list[str] = []
        for key, sub in schema["properties"].items():
            if not key.isidentifier():
                raise ValueError(f"{name}.{key}: not an identifier")
            py, ts = self.of(sub, pascal(name, key))
            py_fields.append(f"    {key}: {py}" if key in required else f"    {key}: NotRequired[{py}]")
            ts_fields.append(f"  {key}{'' if key in required else '?'}: {ts}")
        doc = doc or schema.get("description", "")
        self.py.append("\n".join([f"class {name}(TypedDict):", *([f'    """{doc}"""'] if doc else []), *py_fields]))
        self.ts.append("\n".join([*([f"/** {doc} */"] if doc else []), f"export interface {name} {{", *ts_fields, "}"]))


def load(name: str) -> dict[str, Any]:
    return json.loads((HERE / "schemas" / name).read_text("utf-8"))


def render() -> tuple[str, str]:
    types = Types()
    types.cls(load("manifest.schema.json"), "Manifest")
    py = ('"""Generated by `python -m grain_sdk.generate` from schemas/*.json. Do not edit."""\n'
          "from typing import Any, Literal, NotRequired, TypedDict\n\n\n" + "\n\n\n".join(types.py) + "\n")
    ts = "// Generated by `python -m grain_sdk.generate` from backend/grain_sdk/schemas/*.json. Do not edit.\n\n" + "\n\n".join(types.ts) + "\n"
    return py, ts


def main(argv: list[str]) -> int:
    py, ts = render()
    if "--check" in argv:
        current = (PY_OUT.read_text("utf-8") if PY_OUT.exists() else None, TS_OUT.read_text("utf-8") if TS_OUT.exists() else None)
        if current != (py, ts):
            print("grain_sdk/types.py or packages/ext-sdk/index.d.ts is out of date: run python -m grain_sdk.generate")
            return 1
        return 0
    TS_OUT.parent.mkdir(parents=True, exist_ok=True)
    PY_OUT.write_text(py, "utf-8")
    TS_OUT.write_text(ts, "utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
